"""A small calculator module used to exercise PR review tooling."""

import math


def add(x, y):
    """Return the sum of x and y."""
    return x + y


def subtract(x, y):
    """Return the difference of x and y."""
    return x - y


def divide(a, b):
    """Return the quotient of a and b."""
    return a / b


def square(n):
    """Return n squared."""
    return n * n


def apply_discount(price):
    """Apply a standard discount to a price."""
    return price * 0.85
